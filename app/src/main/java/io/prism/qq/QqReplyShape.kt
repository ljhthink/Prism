package io.prism.qq

import kotlin.random.Random

/**
 * 回复**形状**的代码侧抽样（2026-11-15 新增；ADR-076）。
 *
 * **为什么由代码挑，而不是让模型"注意多样"**：真机 119 条回复里绝大多数是
 * 「20–40 字单段 + 问句收尾」——这不是人设问题，而是模型对"自然、口语、承接话题"
 * 这类指令的**保守解**（每次都选同一种安全形状）。业界实证（Rokabot v3）表明：
 * 由代码轮换回复形状、只把**本轮一条**形状提示交给模型，比要求模型"自己注意多样化"
 * 更能消除模板化。
 *
 * 纯函数 + 可注入随机源，便于单测。
 */
object QqReplyShape {

    /** 一轮只给一条形状提示；不要求模型"每次都不一样"。 */
    private val SHAPES = listOf(
        "这次就一句话接住，别追问，也别解释。",
        "这次先接住他那句，再顺口问一件具体的小事（只问一件）。",
        "这次先给判断或态度，再补一句软的。",
        "这次短一点：半句、一个语气词、一声应，都算说完。",
        "这次可以带一个具体的画面或细节（你眼前/记忆里的），不要堆意象。",
        "这次先说你在做什么/在想什么，再回他。",
        "这次不用总结、不用安慰套路，就把你真实的反应说出来。"
    )

    /**
     * 抽一条形状提示。
     *
     * @param random 注入随机源（测试传确定性实现）
     */
    fun pick(random: Random = Random.Default): String = SHAPES[random.nextInt(SHAPES.size)]

    /** 形状总数（供测试断言覆盖面）。 */
    val size: Int get() = SHAPES.size
}
